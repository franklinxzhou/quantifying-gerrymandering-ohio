# Required crosswalk generated by scripts/mct/build_mct_atoms.py.
function mct_arg(args::Vector{String}, key::String)
    indices = findall(==("--" * key), args)
    length(indices) == 1 || throw(ArgumentError("Expected exactly one --$key"))
    i = only(indices) + 1
    i <= length(args) && !startswith(args[i], "--") ||
        throw(ArgumentError("Missing value after --$key"))
    return args[i]
end
mct_atoms_file = mct_arg(ARGS, "mct_atoms_file")
# Edge multipliers (>= 1) and ousted-population energies (>= 0) are distinct.
# Existing --mct_*_weight flags remain valid aliases for the older energy API.
function mct_optional_arg(args::Vector{String}, key::String)
    indices = findall(==("--" * key), args)
    length(indices) <= 1 || throw(ArgumentError("Duplicate --$key"))
    isempty(indices) && return nothing
    i = only(indices) + 1
    i <= length(args) && !startswith(args[i], "--") ||
        throw(ArgumentError("Missing value after --$key"))
    return args[i]
end
function mct_float_arg(args::Vector{String}, key::String, fallback::Float64)
    text = mct_optional_arg(args, key)
    return text === nothing ? fallback : parse(Float64, text)
end
function mct_lambda_arg(args::Vector{String}, key::String, legacy::String)
    newer = mct_optional_arg(args, key)
    older = mct_optional_arg(args, legacy)
    newer !== nothing && older !== nothing &&
        throw(ArgumentError("Specify either --$key or --$legacy, not both"))
    value = newer === nothing ? older : newer
    return value === nothing ? 0.0 : parse(Float64, value)
end
