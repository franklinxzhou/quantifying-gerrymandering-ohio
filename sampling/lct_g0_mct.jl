function weight_func(g, n1, n2)
    base = edge_weight_func(g, n1, n2;
                            cnty_scale=cnty_w_scale,
                            place_scale=1.0,
                            cnty_field="COUNTY",
                            place_field=nothing)
    return base * mct_edges.multiplier(n1, n2)
end
modify_edge_weights!(base_graph, weight_func);
